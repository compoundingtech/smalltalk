import { expect } from 'vitest'
import type { CollectionSocket } from '@smalltalk/st3-client'
import { ANCHOR_MS } from '../src/kit/time.ts'
import { createReplay, manualClock } from '../src/replay/index.ts'
import { normalizeRecording, type JsonObject, type JsonValue, type RecordingRow } from '../scripts/recordings.ts'
import type { RecordedProof } from './recorded-world.ts'

const jsonValue = (value: unknown): JsonValue => {
  if (value === null || typeof value === 'string' || typeof value === 'boolean') return value
  if (typeof value === 'number' && Number.isFinite(value)) return value
  if (Array.isArray(value)) return value.map((item: unknown) => jsonValue(item))
  if (typeof value === 'object' && value !== null) return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, jsonValue(item)]))
  throw new Error('Replay emitted a non-JSON value')
}
export const jsonObject = (value: unknown): JsonObject => {
  const result = jsonValue(value)
  if (result === null || typeof result !== 'object' || Array.isArray(result)) throw new Error('Replay emitted a non-object')
  return result
}
const text = (value: JsonValue | undefined): string => {
  if (typeof value !== 'string') throw new Error('Expected recorded string')
  return value
}
const exchanges = (rows: readonly RecordingRow[]) => rows.filter((row) => row.kind === 'frame' || row.kind === 'http')

/** Drive recorded inputs only; responses are generated by replay from state/event slices. */
export const assertRecordingFidelity = async (proof: RecordedProof, expected: readonly RecordingRow[]): Promise<void> => {
  const { world, script, rows } = proof
  const clock = manualClock(ANCHOR_MS + Math.min(...rows.map((row) => row.receive_ms)) - 1)
  const replay = createReplay(world, { clock })
  const frames: { at_ms: number; socket_id: string; value: JsonObject }[] = []
  const responses = new Map<number, JsonObject>()
  const sockets = new Map<string, CollectionSocket>()
  const frameRows = expected.filter((row) => row.kind === 'frame')
  try {
    for (const row of rows.filter((row) => row.kind === 'command')) {
      const id = row.socket_id
      if (id === null || sockets.has(id)) continue
      const socket = replay.socket('ws://scenario.invalid/v1/client/collections', ['st3.client.collections.v0'], {})
      socket.onmessage = (event) => {
        if (typeof event.data !== 'string') throw new Error('Replay frame is not JSON text')
        const parsed: unknown = JSON.parse(event.data)
        frames.push({ at_ms: clock.now() - ANCHOR_MS, socket_id: id, value: jsonObject(parsed) })
      }
      sockets.set(id, socket)
    }
    clock.advance(0)
    for (const row of [...rows].sort((a, b) => a.receive_ms - b.receive_ms || a.ordinal - b.ordinal)) {
      clock.advance(ANCHOR_MS + row.receive_ms - clock.now())
      if (row.kind === 'command') {
        if (row.socket_id === null) throw new Error('Command missing socket id')
        const socket = sockets.get(row.socket_id)
        if (socket === undefined) throw new Error('Missing socket')
        if (row.value.kind === 'disconnect') socket.close()
        else socket.send(JSON.stringify(row.value))
      } else if (row.kind === 'http') {
        const method = text(row.value.method)
        const path = text(row.value.path)
        const query = text(row.value.query)
        const requestBody = row.value.request_body
        const response = await replay.fetch('http://scenario.invalid' + path + (query === '' ? '' : '?' + query), {
          method, ...(requestBody === null || requestBody === undefined ? {} : { body: JSON.stringify(requestBody), headers: { 'Content-Type': 'application/json' } }),
        })
        const body: unknown = await response.json()
        responses.set(row.ordinal, { ...row.value, status: response.status, body: jsonObject(body) })
      }
    }
    expect(frames).toHaveLength(frameRows.length)
    const actual = expected.map((row): RecordingRow => {
      if (row.kind === 'http') {
        const value = responses.get(row.ordinal)
        if (value === undefined) throw new Error('Missing HTTP response')
        return { ...row, value }
      }
      if (row.kind !== 'frame') return row
      const index = frameRows.findIndex((frame) => frame.ordinal === row.ordinal)
      const frame = frames[index]
      if (frame === undefined) throw new Error('Missing replay frame')
      return { ...row, receive_ms: frame.at_ms, socket_id: frame.socket_id, value: frame.value }
    })
    const actualExchanges = exchanges(normalizeRecording(script, actual, ANCHOR_MS))
    const expectedExchanges = exchanges(expected)
    expect(actualExchanges).toHaveLength(expectedExchanges.length)
    for (const [index, row] of expectedExchanges.entries()) {
      expect(actualExchanges[index], `Recorded ${row.kind} exchange at ordinal ${row.ordinal}`).toEqual(row)
    }
  } finally { replay.close() }
}
