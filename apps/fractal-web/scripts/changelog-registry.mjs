// Derives the public changelog registry from the directory so a new entry is one new file and no
// shared line. The generated module is never committed: two branches that each add an entry would
// both insert at the top of any sorted checked-in list and conflict, so every consumer regenerates it.
// Usage: node scripts/changelog-registry.mjs [--write | --check]
import { mkdirSync, readdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ChangelogError, changelogEntryIdentity, compareChangelogEntryIds } from '../src/changelog/contract.ts'

export const changelogRegistryDirectory = fileURLToPath(new URL('../.changelog', import.meta.url))
/** Hand-written and generated registry modules; every other file in the directory is an entry. */
export const changelogRegistryModules = Object.freeze(['mod.ts', 'registry.generated.ts'])

/** Entry files of one `.changelog/` directory, newest first. A file that is not an entry fails loudly. */
export const listChangelogEntryFiles = (directory) => readdirSync(directory)
  .filter((file) => !changelogRegistryModules.includes(file))
  .map((file) => ({ file, id: changelogEntryIdentity(file).id }))
  .sort((left, right) => compareChangelogEntryIds(left.id, right.id))
  .map(({ file }) => file)

/** Byte-deterministic for a set of file names, whatever order the directory lists them in. */
export const renderChangelogRegistry = (files) => {
  const sorted = [...files].map((file) => ({ file, id: changelogEntryIdentity(file).id }))
    .sort((left, right) => compareChangelogEntryIds(left.id, right.id)).map(({ file }) => file)
  return [
    '// Generated by scripts/changelog-registry.mjs from the files in this directory. Not tracked by Git.',
    '// Run `pnpm --filter fractal-web changelog:registry` to regenerate; every build and test lane does.',
    ...sorted.map((file, index) => `import * as entry${index} from ${JSON.stringify(`./${file}`)}`),
    '',
    'export const changelogEntryModules = [',
    ...sorted.map((file, index) => `  [${JSON.stringify(file)}, entry${index}],`),
    '] as const',
    '',
  ].join('\n')
}

const generatedPath = (directory) => join(directory, 'registry.generated.ts')
const read = (path) => {
  try {
    return readFileSync(path, 'utf8')
  } catch (error) {
    if (error?.code === 'ENOENT') return undefined
    throw error
  }
}

/** Compares the file on disk with a fresh derivation; `ok` means regenerating gives the same bytes. */
export const checkChangelogRegistry = (directory = changelogRegistryDirectory) => {
  const expected = renderChangelogRegistry(listChangelogEntryFiles(directory))
  const actual = read(generatedPath(directory))
  return actual === expected
    ? { ok: true, reason: 'fresh' }
    : { ok: false, reason: actual === undefined ? 'missing' : 'stale' }
}

/** Writes the generated module when it is missing or differs; replaces it atomically for parallel readers. */
export const writeChangelogRegistry = (directory = changelogRegistryDirectory) => {
  if (checkChangelogRegistry(directory).ok) return { changed: false }
  mkdirSync(directory, { recursive: true })
  const path = generatedPath(directory)
  const temporary = `${path}.${process.pid}.tmp`
  writeFileSync(temporary, renderChangelogRegistry(listChangelogEntryFiles(directory)))
  renameSync(temporary, path)
  return { changed: true }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2] ?? '--write'
  try {
    if (mode === '--check') {
      const { ok, reason } = checkChangelogRegistry()
      if (!ok) {
        console.error(`changelog registry is ${reason}: run \`node apps/fractal-web/scripts/changelog-registry.mjs\``)
        process.exit(1)
      }
      console.log('changelog registry is fresh')
    } else if (mode === '--write') {
      console.log(writeChangelogRegistry().changed ? 'changelog registry written' : 'changelog registry already fresh')
    } else {
      console.error('Usage: node changelog-registry.mjs [--write | --check]')
      process.exit(2)
    }
  } catch (error) {
    console.error(error instanceof ChangelogError ? error.message : error)
    process.exit(1)
  }
}
